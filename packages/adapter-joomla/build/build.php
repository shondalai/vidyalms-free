 * Steps:
 *   1. compile the neutral schema and string catalogue into the component
 *   2. copy packages/core/src into lib_vidyalms_core/src
 *   3. zip every extension, then assemble the package zip
 *   4. with --install-to, drop the package zip into <joomla root>/tmp
 */

declare(strict_types=1);

use Shondalai\VidyaLMS\Tooling\Schema\JoomlaUpdateRules;

// A packager, not a Joomla file: it runs before anything is installed, so no _JEXEC guard.
if (PHP_SAPI !== 'cli') {
    fwrite(STDERR, "build.php runs on the command line only.\n");
    exit(1);
}

if (!class_exists(ZipArchive::class)) {
    fwrite(STDERR, "ERROR: the zip extension is not loaded in " . PHP_BINARY . "\n");
    exit(1);
}

require_once __DIR__ . '/lib/packager.php';

const SQL_BANNER_INSTALL = <<<'SQL'
-- VidyaLMS install schema for Joomla. GENERATED by build/build.php: never edit.
-- Section 1 comes from packages/core/schema/tables.php through
-- tooling/schema/compile.php; section 2 from build/sql/adapter.install.mysql.utf8.sql.


SQL;

const SQL_BANNER_UNINSTALL = <<<'SQL'
-- VidyaLMS uninstall schema for Joomla. GENERATED by build/build.php: never edit.
-- Section 1 comes from build/sql/adapter.uninstall.mysql.utf8.sql; section 2 from
-- packages/core/schema/tables.php through tooling/schema/compile.php.


SQL;

$warnings = [];
$skipped  = [];

// ---------------------------------------------------------------------------
// Arguments and layout
// ---------------------------------------------------------------------------

$adapterDir = dirname(__DIR__);
$repoRoot   = dirname(__DIR__, 3);
$buildDir   = __DIR__;
$stagingDir = $buildDir . '/.generated';

require_once $repoRoot . '/tooling/schema/joomla-update-rules.php';

$outDir     = $adapterDir . '/dist';
$version    = null;
$installTo  = null;
$strict     = false;

foreach (array_slice($argv, 1) as $argument) {
    if (str_starts_with($argument, '--out=')) {
        $outDir = rtrim(substr($argument, 6), '/\\');
    } elseif (str_starts_with($argument, '--work=')) {
        $stagingDir = rtrim(substr($argument, 7), '/\\') . '/generated';
    } elseif (str_starts_with($argument, '--version=')) {
        $version = substr($argument, 10);
    } elseif (str_starts_with($argument, '--install-to=')) {
        $installTo = rtrim(substr($argument, 13), '/\\');
    } elseif ($argument === '--strict') {
        $strict = true;
    } elseif ($argument === '--help' || $argument === '-h') {
        out('Usage: php build/build.php [--out=<dir>] [--version=X.Y.Z] [--install-to=<joomla root>] [--strict]');
        exit(0);
    } else {
        fail('Unknown argument: ' . $argument);
    }
}

if ($version !== null && preg_match('/^\d+\.\d+\.\d+([-.][A-Za-z0-9.]+)?$/', $version) !== 1) {
    fail('--version must look like X.Y.Z, got: ' . $version);
}

$coreSrc          = $repoRoot . '/packages/core/src';
$coreAutoload     = $repoRoot . '/packages/core/vendor/autoload.php';
$schemaCompiler   = $repoRoot . '/tooling/schema/compile.php';
$i18nCompiler     = $repoRoot . '/tooling/i18n/compile.php';
$packageManifest  = $adapterDir . '/pkg_vidyalms.xml';
$packageScript    = $adapterDir . '/pkg_script.php';
$libraryDir       = $adapterDir . '/lib_vidyalms_core';
$componentDir     = $adapterDir . '/com_vidyalms';
$pluginsDir       = $adapterDir . '/plugins';

foreach (
    [
        'core sources'      => $coreSrc,
        'library extension' => $libraryDir,
    ] as $label => $required
) {
    if (!is_dir($required)) {
        fail('Missing ' . $label . ': ' . slashes($required));
    }
}

foreach (
    [
        'package manifest'    => $packageManifest,
        'package script'      => $packageScript,
        'library manifest'    => $libraryDir . '/vidyalms_core.xml',
        'schema compiler'     => $schemaCompiler,
        'i18n compiler'       => $i18nCompiler,
    ] as $label => $required
) {
    if (!is_file($required)) {
        fail('Missing ' . $label . ': ' . slashes($required));
    }
}

if (!is_file($coreAutoload)) {
    fail(
        'packages/core/vendor/autoload.php is missing, and the schema compiler needs it. '
        . 'Run: composer install --working-dir=' . slashes($repoRoot . '/packages/core'),
    );
}

$manifestXml = simplexml_load_file($packageManifest);

if ($manifestXml === false) {
    fail('Cannot parse ' . slashes($packageManifest));
}

$manifestVersion = trim((string) $manifestXml->version);

if ($manifestVersion === '') {
    fail('No <version> in ' . slashes($packageManifest));
}

$version ??= $manifestVersion;

out('VidyaLMS Joomla packager');
out('  repository : ' . slashes($repoRoot));
out('  adapter    : ' . slashes($adapterDir));
out('  output     : ' . slashes($outDir));
out('  version    : ' . $version . ($version === $manifestVersion ? '' : ' (manifest says ' . $manifestVersion . ')'));
out('  php        : ' . PHP_VERSION . ' at ' . slashes(PHP_BINARY));

ensureDirectory($outDir);
ensureDirectory($stagingDir);

// ---------------------------------------------------------------------------
// Step 1: compile the schema and the string catalogue into the component
// ---------------------------------------------------------------------------

step('Step 1: compile schema and language catalogue');

$schemaStaging = $stagingDir . '/schema';
$i18nStaging   = $stagingDir . '/i18n';

removeTree($schemaStaging);
removeTree($i18nStaging);
ensureDirectory($schemaStaging);
ensureDirectory($i18nStaging);

runPhpScript($schemaCompiler, ['--out=' . $schemaStaging]);
runPhpScript($i18nCompiler, ['--out=' . $i18nStaging]);

$generatedInstall   = $schemaStaging . '/joomla/install.mysql.utf8.sql';
$generatedUninstall = $schemaStaging . '/joomla/uninstall.mysql.utf8.sql';
$generatedIni       = $i18nStaging . '/en-GB.com_vidyalms.ini';

foreach ([$generatedInstall, $generatedUninstall, $generatedIni] as $produced) {
    if (!is_file($produced)) {
        fail('The compilers did not produce ' . slashes($produced));
    }
}

if (is_dir($componentDir)) {
    // The shipped install script is the generated core schema plus the
    // adapter's own tables; the uninstall script drops the adapter tables
    // first, so nothing outlives the extension it belongs to.
    $adapterInstall   = $buildDir . '/sql/adapter.install.mysql.utf8.sql';
    $adapterUninstall = $buildDir . '/sql/adapter.uninstall.mysql.utf8.sql';

    foreach (['adapter install SQL' => $adapterInstall, 'adapter uninstall SQL' => $adapterUninstall] as $label => $required) {
        if (!is_file($required)) {
            fail('Missing ' . $label . ': ' . slashes($required));
        }
    }

    $sqlDir = $componentDir . '/admin/sql';
    ensureDirectory($sqlDir);

    file_put_contents(
        $sqlDir . '/install.mysql.utf8.sql',
        SQL_BANNER_INSTALL
        . "-- SECTION 1: core tables, generated from packages/core/schema/tables.php.\n\n"
        . rtrim((string) file_get_contents($generatedInstall)) . "\n\n"
        . rtrim((string) file_get_contents($adapterInstall)) . "\n",
    );

    file_put_contents(
        $sqlDir . '/uninstall.mysql.utf8.sql',
        SQL_BANNER_UNINSTALL
        . rtrim((string) file_get_contents($adapterUninstall)) . "\n\n"
        . "-- SECTION 2: core tables, generated from packages/core/schema/tables.php.\n\n"
        . rtrim((string) file_get_contents($generatedUninstall)) . "\n",
    );

    out('   SQL     -> ' . relative($sqlDir, $adapterDir) . '/{install,uninstall}.mysql.utf8.sql (core + adapter)');

    // The install script always creates the current shape, so a site that
    // installs clean is never wrong. A site that upgrades gets nothing but
    // what the update folder holds, and the failure is silent until it writes
    // to a column it never got, on the upgraded sites and nowhere else.
    //
    // What makes the declared version reachable is the floor, not a chain. A
    // site can only upgrade from a version it already holds, and the oldest
    // version any site holds is tooling/schema/floor.php, because that is the
    // version the first release installs at and nothing shipped below it. So
    // the install itself reaches the floor, and every version above the floor
    // needs an update script. The three refusals below are that sentence.
    $schemaVersion = (string) require $repoRoot . '/tooling/schema/version.php';
    $schemaFloor   = (string) require $repoRoot . '/tooling/schema/floor.php';
    $updateDir     = $sqlDir . '/updates/mysql';
    $updateFile    = $updateDir . '/' . $schemaVersion . '.sql';

    if (version_compare($schemaVersion, $schemaFloor, '<')) {
        fail(
            'Schema version ' . $schemaVersion . ' (tooling/schema/version.php) is below the install floor '
            . $schemaFloor . ' (tooling/schema/floor.php), which no shipped site can be at.',
        );
    }

    // Joomla stamps #__schemas with the highest name in this folder on install,
    // and SchemaVersion::shipped() reads the same highest name to write the
    // neutral schema_version row, so the folder has to hold a file for the
    // declared version even when the install is what actually creates it. At
    // the floor that file is a marker carrying no statements.
    if (!is_file($updateFile)) {
        fail(
            'Schema version ' . $schemaVersion . ' (tooling/schema/version.php) has no update script: '
            . slashes($updateFile) . ' does not exist.'
            . ($schemaVersion === $schemaFloor
                ? ' At the install floor that file is the marker the installer records the version from.'
                : ''),
        );
    }

    // Every file has to survive being run twice. On the component route that is
    // hygiene rather than necessity, because the extension row and its
    // #__schemas row survive an update and parseSchemaUpdates skips what it has
    // already recorded; on the Pro library route the row does not survive and
    // the whole folder re-runs on every upgrade. One rule on both, out of
    // tooling/schema/joomla-update-rules.php, because "a site that lost its
    // #__schemas row" is a real state on this host too and a file that cannot
    // be re-run turns it into an aborted install.
    foreach ((array) scandir($updateDir) as $entry) {
        if (!\is_string($entry) || preg_match('/^(\d+\.\d+\.\d+)\.sql$/', $entry, $parts) !== 1) {
            continue;
        }

        $updateProblems = JoomlaUpdateRules::problemsIn(
            (string) file_get_contents($updateDir . '/' . $entry),
            'sql/updates/mysql/' . $entry,
        );

        if ($updateProblems !== []) {
            fail(implode("\n       ", $updateProblems));
        }

        if (version_compare($parts[1], $schemaVersion, '>')) {
            fail(
                'sql/updates/mysql/' . $entry . ' is above the schema version ' . $schemaVersion
                . ', so a fresh install would record a version it never installed.',
            );
        }

        if (version_compare($parts[1], $schemaFloor, '<')) {
            fail(
                'sql/updates/mysql/' . $entry . ' is below the install floor ' . $schemaFloor
                . ', so no site would ever run it.',
            );
        }
    }

    out('   schema  '  . $schemaVersion . ' -> ' . relative($updateFile, $adapterDir)
        . ' (floor ' . $schemaFloor . ')');

    // The other host, asked from here. README.md says all four packagers refuse
    // a version either host cannot reach, and until now only the two WordPress
    // ones asked: a Joomla build with Activator::SCHEMA_VERSION left behind
    // would pass, ship, and leave every WordPress site one version short with
    // nothing in either build log to say so. On that host dbDelta reaches the
    // shape from the constant alone, so the constant IS its update path.
    $wordpressActivator = $repoRoot . '/packages/adapter-wordpress/vidyalms/src/Setup/Activator.php';

    if (is_file($wordpressActivator)) {
        $activatorBody = (string) file_get_contents($wordpressActivator);

        if (preg_match("/const\s+SCHEMA_VERSION\s*=\s*'([^']+)'/", $activatorBody, $activatorFound) !== 1) {
            fail('Cannot read SCHEMA_VERSION from ' . slashes($wordpressActivator) . '.');
        }

        if ($activatorFound[1] !== $schemaVersion) {
            fail(
                'WordPress\\Setup\\Activator::SCHEMA_VERSION is ' . $activatorFound[1] . ' but '
                . 'tooling/schema/version.php says ' . $schemaVersion . '. A WordPress site upgrading to '
                . $schemaVersion . ' would run neither dbDelta nor the migrations for it.',
            );
        }

        out('   schema  ' . $schemaVersion . ' -> WordPress\\Setup\\Activator::SCHEMA_VERSION (the other host)');
    } else {
        warn('packages/adapter-wordpress is not present, so the WordPress schema version was not checked');
    }

    // The generated strings are mirrored into a marked block of the
    // administrator catalogue, which is the one file Joomla loads for
    // com_vidyalms. JoomlaTranslator loads it from JPATH_ADMINISTRATOR in
    // every application, so the site catalogue needs no copy.
    $targetIni = $componentDir . '/admin/language/en-GB/com_vidyalms.ini';

    if (is_file($targetIni)) {
        mergeGeneratedIni($targetIni, (string) file_get_contents($generatedIni), 'packages/core/i18n/catalogue.php');
        out('   merge   -> ' . relative($targetIni, $adapterDir) . ' (generated block rebuilt)');
    } else {
        warn(
            relative($targetIni, $adapterDir) . ' does not exist, so the generated core strings are not'
            . ' shipped; the component must provide that catalogue for the merge to happen',
        );
    }
} else {
    warn('com_vidyalms is not present yet; SQL and language output stayed in build/.generated');
}

// ---------------------------------------------------------------------------
// Step 2: copy the core into the library extension
// ---------------------------------------------------------------------------

step('Step 2: copy the core into lib_vidyalms_core/src');

$librarySrc = $libraryDir . '/src';
removeTree($librarySrc);
ensureDirectory($librarySrc);

$copied = copyTree($coreSrc, $librarySrc);
out('   ' . $copied . ' files copied from ' . relative($coreSrc, $repoRoot));

assertTreesMatch($coreSrc, $librarySrc, 'packages/core/src');

// The certificate PDF runtime ships in the Pro library and nowhere in this
// package: free certificates are HTML, and VidyaLMS Pro seats its PDF port at
// the ports-ready seam. A runtime an earlier build left here is removed so it
// can never ride along in the zip, and a manifest that still lists the folder
// fails the build, because Joomla would refuse to install a library whose
// manifest names a folder the zip does not carry.
removeTree($libraryDir . '/pdf-runtime');

if (str_contains((string) file_get_contents($libraryDir . '/vidyalms_core.xml'), 'pdf-runtime')) {
    fail('lib_vidyalms_core/vidyalms_core.xml still lists pdf-runtime, which ships only in lib_vidyalms_pro.');
}

out('   no certificate PDF runtime: it ships with VidyaLMS Pro');

// ---------------------------------------------------------------------------
// Step 2b: bundle the React apps (packages/ui) into com_vidyalms/media/app
// ---------------------------------------------------------------------------

step('Step 2b: bundle the React apps');

$uiDir      = $repoRoot . '/packages/ui';
$uiDist     = $uiDir . '/dist';
$appTarget  = $componentDir . '/media/app';

// Native entry URLs are versioned by the host. All secondary chunks are
// content-hashed; validate the entire manifest graph, not historical filenames.
require_once $repoRoot . '/tooling/releases/ui-manifest.php';
$uiEntries = [];
try {
    $uiEntries = vidyalmsUiManifestFiles($uiDist);
    $distComplete = true;
} catch (RuntimeException | JsonException $error) {
    $distComplete = false;
    out('   incomplete UI bundle: ' . $error->getMessage());
}

$distStale = false;

if ($distComplete) {
    $sourcesNewest = newestMtime([
        $uiDir . '/src',
        $uiDir . '/scripts',
        $uiDir . '/package.json',
        $uiDir . '/vite.config.ts',
        $uiDir . '/tailwind.config.ts',
        $uiDir . '/postcss.config.js',
        $repoRoot . '/packages/api-sdk/src',
        $repoRoot . '/packages/api-sdk/package.json',
    ]);

    $distOldest = PHP_INT_MAX;

    foreach ($uiEntries as $entry) {
        $distOldest = min($distOldest, (int) filemtime($uiDist . '/' . $entry));
    }

    $distStale = $sourcesNewest > $distOldest;
}

if (!is_dir($uiDir)) {
    warn('packages/ui does not exist; the React apps are not shipped');
} else {
    if (!$distComplete || $distStale) {
        if (!npmAvailable()) {
            warn(
                'packages/ui/dist is ' . ($distComplete ? 'stale' : 'missing or incomplete')
                . ' and npm is not available; '
                . ($distComplete ? 'shipping the stale bundle' : 'the React apps are not shipped'),
            );
        } else {
            out('   dist is ' . ($distComplete ? 'stale' : 'missing or incomplete') . '; running npm run build');

            if (runCommand('npm run build', $uiDir) !== 0) {
                fail('npm run build failed in ' . slashes($uiDir));
            }

            try {
                // Re-read: a rebuild can change every secondary chunk filename.
                $uiEntries = vidyalmsUiManifestFiles($uiDist);
                $distComplete = true;
            } catch (RuntimeException | JsonException $error) {
                fail('npm run build produced an incomplete UI bundle: ' . $error->getMessage());
            }
        }
    }

    // The manifest lists media/app unconditionally, and the Joomla installer
    // refuses a media folder the zip does not carry, so the folder always
    // exists; the guard file also keeps it non-empty for the zip.
    removeTree($appTarget);
    ensureDirectory($appTarget);
    file_put_contents($appTarget . '/index.html', "<!DOCTYPE html><title></title>\n");

    if ($distComplete) {
        // media/app/js and media/app/css, because Joomla's relative asset
        // resolution ("com_vidyalms/app/player.js") inserts the js/ or css/
        // folder between the subfolder and the file. All JS lands in one
        // directory so the entries' relative ESM imports (./shared.js,
        // ./vendor.js) keep resolving.
        ensureDirectory($appTarget . '/js');
        ensureDirectory($appTarget . '/css');

        $shipped = 0;

        foreach (fileList($uiDist) as $file) {
            if (str_ends_with($file, '.css') || str_ends_with($file, '.woff2')) {
                $destination = $appTarget . '/css/' . $file;
            } elseif (str_ends_with($file, '.js')) {
                $destination = $appTarget . '/js/' . $file;
            } else {
                continue;
            }

            if (!copy($uiDist . '/' . $file, $destination)) {
                fail('Cannot copy ' . slashes($uiDist . '/' . $file));
            }

            $shipped++;
        }

        require_once $repoRoot . '/tooling/releases/frontend-notices.php';
        vidyalmsFrontendNotices($repoRoot, $appTarget);
        out('   ' . $shipped . ' app files copied into ' . relative($appTarget, $adapterDir) . '/{js,css}');
    }
}

// ---------------------------------------------------------------------------
// Step 3: zip every extension, then assemble the package
// ---------------------------------------------------------------------------

step('Step 3: build the extension zips');

/** @var array<string, string> $children zip file name => absolute source directory */
$children = [];

foreach ($manifestXml->files->file as $file) {
    $zipName = trim((string) $file);

    if ($zipName === '') {
        continue;
    }

    $name = basename($zipName, '.zip');

    if (str_starts_with($name, 'plg_')) {
        $children[$zipName] = $pluginsDir . '/' . $name;
    } elseif (str_starts_with($name, 'mod_')) {
        $children[$zipName] = $adapterDir . '/modules/' . $name;
    } else {
        $children[$zipName] = $adapterDir . '/' . $name;
    }
}

if ($children === []) {
    fail('No <file> entries in ' . slashes($packageManifest));
}

/** @var array<string, string> $built zip file name => absolute zip path */
$built = [];

foreach ($children as $zipName => $sourceDirectory) {
    $zipPath = $outDir . '/' . $zipName;

    // An extension directory another agent has created but not filled would
    // otherwise become an empty, uninstallable zip.
    $empty = is_dir($sourceDirectory) && fileList($sourceDirectory) === [];

    if (!is_dir($sourceDirectory) || $empty) {
        $skipped[] = $zipName;
        warn(
            $zipName . ' skipped: ' . relative($sourceDirectory, $adapterDir)
            . ($empty ? ' is empty' : ' does not exist yet'),
        );

        // Drop the zip an earlier run may have left, so dist never ships a stale extension.
        if (is_file($zipPath)) {
            unlink($zipPath);
        }

        continue;
    }

    // Joomla decides whether to upgrade an extension by comparing the version
    // in its own manifest, so a release stamps every child, not just the
    // package. The rewrite happens on the copy inside the zip; manifests on
    // disk stay at their committed version.
    $restamped = restampManifest($sourceDirectory, $version);

    if ($zipName === 'com_vidyalms.zip') {
        $restamped += restampAssetJson($sourceDirectory, $version);
    }

    $entries = makeZip($zipPath, $sourceDirectory, ['LICENSE' => $repoRoot . '/LICENSE'], $restamped);
    $built[$zipName] = $zipPath;
    out(sprintf(
        '   %-32s %4d files  %s%s',
        $zipName,
        $entries,
        humanSize((int) filesize($zipPath)),
        $restamped === [] ? '' : '  version ' . $version,
    ));
}

// A plugin directory nobody packages is a bug in the manifest, not a silent omission.
if (is_dir($pluginsDir)) {
    foreach (glob($pluginsDir . '/plg_*', GLOB_ONLYDIR) ?: [] as $directory) {
        $zipName = basename($directory) . '.zip';

        if (!isset($children[$zipName])) {
            warn($zipName . ' exists under plugins/ but is not listed in pkg_vidyalms.xml');
        }
    }
}

step('Step 3b: assemble the package');

$packageZip  = null;
$packageName = 'pkg_vidyalms-' . $version . '.zip';

if ($skipped !== []) {
    warn(
        'package not assembled: ' . count($skipped) . ' of ' . count($children)
        . ' extensions are still missing (' . implode(', ', $skipped) . ')',
    );

    if (is_file($outDir . '/' . $packageName)) {
        unlink($outDir . '/' . $packageName);
        out('   removed the stale ' . $packageName . ' from a previous run');
    }
} else {
    $manifestBody = (string) file_get_contents($packageManifest);

    if ($version !== $manifestVersion) {
        $manifestBody = preg_replace(
            '/<version>[^<]*<\/version>/',
            '<version>' . $version . '</version>',
            $manifestBody,
            1,
        ) ?? $manifestBody;
    }

    $extraFiles = [
        'pkg_script.php' => $packageScript,
        'LICENSE' => $repoRoot . '/LICENSE',
        'language/en-GB/pkg_vidyalms.sys.ini' => $adapterDir . '/language/en-GB/pkg_vidyalms.sys.ini',
    ];

    foreach ($built as $zipName => $zipPath) {
        $extraFiles['packages/' . $zipName] = $zipPath;
    }

    $packageZip = $outDir . '/' . $packageName;
    $entries    = makeZip($packageZip, null, $extraFiles, ['pkg_vidyalms.xml' => $manifestBody]);
    $packageBytes = (int) filesize($packageZip);
    out(sprintf('   %-32s %4d entries %s', $packageName, $entries, humanSize($packageBytes)));
    out(sprintf('   %-32s %s bytes of %s', 'JED upload limit', number_format($packageBytes), number_format(JOOMLA_JED_UPLOAD_LIMIT)));

    // A free package the JED cannot accept is not a release, so this is a
    // failure rather than a line in the log.
    if ($packageBytes >= JOOMLA_JED_UPLOAD_LIMIT) {
        fail('The Joomla free package must be smaller than the JED 7 MB upload limit.');
    }
}

// ---------------------------------------------------------------------------
// Step 4: hand the package to a Joomla root
// ---------------------------------------------------------------------------

if ($installTo !== null) {
    step('Step 4: stage the package for installation');

    if (!is_file($installTo . '/configuration.php') && !is_file($installTo . '/cli/joomla.php')) {
        fail('--install-to does not look like a Joomla root: ' . slashes($installTo));
    }

    if ($packageZip === null) {
        fail('Nothing to install: the package could not be assembled.');
    }

    $tmpDir = $installTo . '/tmp';
    ensureDirectory($tmpDir);

    $staged = $tmpDir . '/' . $packageName;

    if (!copy($packageZip, $staged)) {
        fail('Cannot copy the package into ' . slashes($tmpDir));
    }

    out('   staged: ' . slashes($staged));
    out('   install it with:');
    out('     php ' . slashes($installTo . '/cli/joomla.php') . ' extension:install --path=' . slashes($staged));
}

// ---------------------------------------------------------------------------
// Summary
// ---------------------------------------------------------------------------

step('Summary');

foreach ($built as $zipName => $zipPath) {
    out('   built   ' . relative($zipPath, $repoRoot));
}

if ($packageZip !== null) {
    out('   built   ' . relative($packageZip, $repoRoot));
}

foreach ($skipped as $zipName) {
    out('   skipped ' . $zipName);
}

out();
out(sprintf(
    '%d extension zip(s), %d skipped, %d warning(s).',
    count($built),
    count($skipped),
    count($warnings),
));

if ($built === []) {
    fail('Nothing was built.');
}

if ($strict && ($skipped !== [] || $warnings !== [])) {
    fail('--strict: the build finished with ' . count($skipped) . ' skipped extension(s) and ' . count($warnings) . ' warning(s).');
}

exit(0);

/**
 * Asserts that a copied tree is byte for byte the tree it was copied from.
 *
 * The same rule the two Pro packagers already run, applied to the free core.
 * The copy is a build artefact living inside the extension directory the
 * packager zips, which is exactly the shape a stale or hand-edited copy hides
 * in: a review reads it as source, a hand edit survives until the next packager
 * run overwrites it, and a copy that was never refreshed ships a version of the
 * code nobody has looked at. Hashing after the copy makes that drift impossible
 * rather than unlikely, and the copy is gitignored so the two halves hold
 * together.
 */
function assertTreesMatch(string $source, string $target, string $label): void
{
    $hashes = static function (string $root): array {
        $out = [];

        foreach (fileList($root) as $relative) {
            $out[$relative] = (string) hash_file('sha256', $root . '/' . $relative);
        }

        ksort($out);

        return $out;
    };

    $from = $hashes($source);
    $to = $hashes($target);

    if ($from === $to) {
        out('   verified -> ' . count($from) . ' files match ' . $label . ' byte for byte');

        return;
    }

    $differences = [];

    foreach (array_keys($from + $to) as $file) {
        if (($from[$file] ?? null) !== ($to[$file] ?? null)) {
            $differences[] = (string) $file;
        }
    }

    fail(
        'The copy of ' . $label . ' does not match its source: '
        . implode(', ', array_slice($differences, 0, 5))
        . (count($differences) > 5 ? ' and ' . (count($differences) - 5) . ' more' : '')
    );
}
