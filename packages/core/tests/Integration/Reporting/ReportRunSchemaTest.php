<?php

declare(strict_types=1);

namespace Shondalai\VidyaLMS\Core\Tests\Integration\Reporting;

use PHPUnit\Framework\TestCase;
use Shondalai\VidyaLMS\Core\Domain\Reporting\ReportRun;

/**
 * `report_runs` against the schema the two install paths are meant to
 * reproduce.
 *
 * The comparison used to run against the migrations that created and then
 * amended the table, and it read both rather than only the creating one,
 * because a column added by a later migration is still a column the install
 * creates and pinning the check to the first would have let an amendment ship
 * on one host and not the other.
 *
 * R13 removed both: the product had never been released, so the chain
 * described upgrades nobody ran, and the history collapsed into one compiled
 * install. The drift the test existed to catch did not go with it, it moved:
 * the two artefacts are now generated by two compilers from one authority, and
 * a column the Joomla script creates and the WordPress schema forgets is still
 * invisible until the first write to it fails, on one host and nowhere else.
 */
final class ReportRunSchemaTest extends TestCase
{
    private const JOOMLA_INSTALL =
        __DIR__ . '/../../../../../packages/adapter-joomla/com_vidyalms/admin/sql/install.mysql.utf8.sql';

    private const WORDPRESS_SCHEMA =
        __DIR__ . '/../../../../../packages/adapter-wordpress/vidyalms/schema/schema.php';

    private const VERSION = __DIR__ . '/../../../../../tooling/schema/version.php';

    private const FLOOR = __DIR__ . '/../../../../../tooling/schema/floor.php';

    /** The table's own CREATE block out of the Joomla install script. */
    private static function joomlaBlock(): string
    {
        $sql = file_get_contents(self::JOOMLA_INSTALL);
        self::assertIsString($sql, 'the Joomla install script is missing');
        $found = [];

        self::assertSame(
            1,
            preg_match(
                '/CREATE TABLE IF NOT EXISTS `#__vidyalms_report_runs` \([\s\S]*?\n\)[^;]*;/',
                str_replace("\r\n", "\n", $sql),
                $found,
            ),
            'report_runs is not created once by the Joomla install',
        );

        $block = (string) ($found[0] ?? '');
        self::assertNotSame('', $block, 'the report_runs block is empty');

        return $block;
    }

    /** The table's own CREATE statement out of the compiled WordPress schema. */
    private static function wordpressBlock(): string
    {
        /** @var mixed $statements */
        $statements = require self::WORDPRESS_SCHEMA;
        self::assertIsArray($statements);

        foreach ($statements as $statement) {
            self::assertIsString($statement);

            if (str_starts_with($statement, 'CREATE TABLE `{prefix}vidyalms_report_runs`')) {
                return $statement;
            }
        }

        self::fail('report_runs is not declared by the compiled WordPress schema');
    }

    /** @return array<string, mixed> */
    private static function table(): array
    {
        /** @var array<string, array<string, mixed>> $schema */
        $schema = require __DIR__ . '/../../../schema/tables.php';

        self::assertArrayHasKey('report_runs', $schema, 'report_runs is declared in the neutral schema');

        return $schema['report_runs'];
    }

    public function testTheJoomlaInstallDeclaresEveryColumnTheSchemaDoes(): void
    {
        $block = self::joomlaBlock();

        /** @var array<string, mixed> $columns */
        $columns = self::table()['columns'];

        foreach (array_keys($columns) as $column) {
            self::assertSame(
                1,
                substr_count($block, '`' . $column . '` '),
                sprintf('the install creates report_runs without "%s"', $column),
            );
        }

        // The two the whole manifest turns on. A nullable expires_at is skipped
        // by the sweep for the life of the site, and a nullable timezone means
        // a period-bounded extract cannot be regenerated identically.
        self::assertStringContainsString('`expires_at` DATETIME NOT NULL', $block);
        self::assertStringContainsString('`timezone` VARCHAR(64) NOT NULL', $block);
        self::assertStringContainsString('`scope_digest` VARCHAR(64) NOT NULL', $block);
    }

    public function testTheJoomlaInstallDeclaresEveryIndexTheSchemaDoes(): void
    {
        $block = self::joomlaBlock();

        /** @var list<array{columns: list<string>}> $indexes */
        $indexes = self::table()['indexes'];

        foreach ($indexes as $index) {
            self::assertStringContainsString(
                '(`' . implode('`, `', $index['columns']) . '`)',
                $block,
                'the install creates report_runs without the index on ' . implode(', ', $index['columns']),
            );
        }
    }

    public function testTheWordPressSchemaDeclaresEveryColumnAndIndex(): void
    {
        $block = self::wordpressBlock();

        /** @var array<string, mixed> $columns */
        $columns = self::table()['columns'];

        foreach (array_keys($columns) as $column) {
            self::assertSame(
                1,
                substr_count($block, '`' . $column . '` '),
                sprintf('the WordPress schema declares report_runs without "%s"', $column),
            );
        }

        /** @var list<array{columns: list<string>}> $indexes */
        $indexes = self::table()['indexes'];

        foreach ($indexes as $index) {
            self::assertStringContainsString('(`' . implode('`, `', $index['columns']) . '`)', $block);
        }
    }

    /**
     * The sweep and the owner lookup each have an index, on both hosts.
     *
     * dbDelta is documented as unreliable about new indexes, so the deleted
     * migration ran a query that used one rather than trusting the CREATE they
     * were declared in. There is no migration to run a query from any more, and
     * an install declares its indexes inside the CREATE where dbDelta is at its
     * most reliable, so what is left worth checking is that both hosts declare
     * the two the sweep and the run list would otherwise scan the table for.
     */
    public function testBothHostsIndexTheSweepAndTheOwnerLookup(): void
    {
        foreach ([self::joomlaBlock(), self::wordpressBlock()] as $block) {
            self::assertStringContainsString('KEY `report_runs_expires_at_ix` (`expires_at`)', $block);
            self::assertStringContainsString(
                'KEY `report_runs_requested_by_created_at_ix` (`requested_by`, `created_at`)',
                $block,
            );
        }

        // And the two hosts declare the table identically, header aside, which
        // is the comparison the two deleted migrations were a proxy for.
        $joomla = self::joomlaBlock();
        $wordpress = self::wordpressBlock();
        $body = static function (string $block): string {
            $opens = strpos($block, "(\n");
            self::assertNotFalse($opens);

            return substr($block, $opens);
        };

        self::assertSame($body($joomla), $body($wordpress));
    }

    public function testTheRepositorySchemaVersionIsReachableFromTheInstallFloor(): void
    {
        $version = require self::VERSION;
        $floor = require self::FLOOR;

        self::assertIsString($version);
        self::assertIsString($floor);
        // The repository's version has to be one a site can hold. Before the
        // history was collapsed that meant the pin had to have reached the
        // newest migration touching this table; now it means the pin is at or
        // above the version the first release installs at, because that is the
        // only version a site can have installed at and the install creates
        // this table.
        self::assertGreaterThanOrEqual(
            0,
            version_compare($version, $floor),
            'a version below the install floor is a version no site can be at',
        );
    }

    /** The state vocabulary the schema comment declares and the domain enumerates are one list. */
    public function testTheStateVocabularyIsTheOneTheDomainDeclares(): void
    {
        self::assertSame(
            ['queued', 'running', 'done', 'empty', 'failed', 'expired'],
            ReportRun::STATES,
        );
    }
}
