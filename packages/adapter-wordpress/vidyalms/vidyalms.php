defined('ABSPATH') || exit;

// A second copy of this file in the plugins directory would otherwise redeclare
// everything below and take the site down with a fatal.
if (defined('VIDYALMS_VERSION')) {
    return;
}

define('VIDYALMS_VERSION', '1.0.1');
define('VIDYALMS_MINIMUM_PHP', '8.1');

/*
 * WordPress honours the "Requires PHP" header when activating and updating, but
 * not when a host moves an already active site to an older PHP. Everything past
 * this point uses syntax that would be a parse error there, so the plugin says
 * so and stops instead.
 */
if (version_compare(PHP_VERSION, VIDYALMS_MINIMUM_PHP, '<')) {
    add_action('admin_notices', function () {
        printf(
            '<div class="notice notice-error"><p>%s</p></div>',
            esc_html(
                sprintf(
                    /* translators: 1: required PHP version, 2: running PHP version */
                    __('VidyaLMS needs PHP %1$s or newer. This site runs PHP %2$s.', 'vidyalms'),
                    VIDYALMS_MINIMUM_PHP,
                    PHP_VERSION
                )
            )
        );
    });

    return;
}

define('VIDYALMS_PLUGIN_FILE', __FILE__);
define('VIDYALMS_PLUGIN_DIR', plugin_dir_path(__FILE__));
define('VIDYALMS_PLUGIN_URL', plugin_dir_url(__FILE__));

// Order access goes exclusively through WooCommerce CRUD, including HPOS stores.
add_action('before_woocommerce_init', static function (): void {
    if (class_exists(\Automattic\WooCommerce\Utilities\FeaturesUtil::class)) {
        \Automattic\WooCommerce\Utilities\FeaturesUtil::declare_compatibility('custom_order_tables', __FILE__, true);
    }
});

/**
 * The plugin's own PSR-4 loader, for Shondalai\VidyaLMS\WordPress.
 *
 * The core and the vendored PSR interfaces bring their own generated loaders
 * (core/autoload.php and vendor-psr/autoload.php); this one covers src/ and
 * nothing else, so a class name outside the namespace is left to whoever else
 * is registered.
 */
function vidyalms_autoload(string $class): void
{
    $prefix = 'Shondalai\\VidyaLMS\\WordPress\\';

    if (strncmp($class, $prefix, strlen($prefix)) !== 0) {
        return;
    }

    $relative = substr($class, strlen($prefix));
    $file = VIDYALMS_PLUGIN_DIR . 'src/' . str_replace('\\', '/', $relative) . '.php';

    if (is_readable($file)) {
        require_once $file;
    }
}

spl_autoload_register('vidyalms_autoload');

/**
 * The PSR interfaces first, because the core type-hints them, then the core.
 * Both files are generated by build/build.php; vendor-psr/autoload.php declares
 * a package only when the site does not already provide it, so a site running
 * its own Composer autoloader keeps its copy.
 */
foreach (['vendor-psr/autoload.php', 'core/autoload.php'] as $vidyalms_loader) {
    $vidyalms_loader = VIDYALMS_PLUGIN_DIR . $vidyalms_loader;

    if (is_readable($vidyalms_loader)) {
        require_once $vidyalms_loader;
    }
}

unset($vidyalms_loader);

register_activation_hook(__FILE__, ['Shondalai\\VidyaLMS\\WordPress\\Setup\\Activator', 'activate']);
register_deactivation_hook(__FILE__, ['Shondalai\\VidyaLMS\\WordPress\\Setup\\Deactivator', 'deactivate']);

/**
 * The shared learning engine for this request.
 *
 * The documented way into the core from anywhere in WordPress: a theme, another
 * plugin, a WP-CLI command, a scheduled job. There is exactly one kernel per
 * request; asking twice returns the same object.
 *
 * @return \Shondalai\VidyaLMS\Core\Boot\CoreKernel
 */
function vidyalms_kernel()
{
    return \Shondalai\VidyaLMS\WordPress\Plugin::kernel();
}

/**
 * The shared port bundle, for code that needs one service rather than the whole
 * engine.
 *
 * @return \Shondalai\VidyaLMS\Core\Port\Ports
 */
function vidyalms_ports()
{
    return \Shondalai\VidyaLMS\WordPress\Plugin::ports();
}

/**
 * The actor background work runs as, for a grant that arrives without a logged
 * in user: a completed order from a payment webhook, a queued expiry, a CLI
 * import. Null when the site has no administrator to stand in.
 *
 * @return \Shondalai\VidyaLMS\Core\Application\Shared\Principal|null
 */
function vidyalms_system_principal()
{
    return \Shondalai\VidyaLMS\WordPress\Plugin::systemPrincipal();
}

